  function langOf(personaId) {
    const st = A.state;
    if (!st) return 'en';
    const p = st.personas && st.personas[personaId || st.current];
    return (p && p.lang) || 'en';
  }

  A.i18n = { STR, langOf };

  /* t(key, vars, lang) — lang defaults to the current persona's language */
  A.t = function (key, vars, lang) {
    const L = lang || langOf();
    const row = STR[key];
    if (!row) { console.warn('[i18n] missing key', key); return key; }
    if (L === 'hi') return A.util.fill(row[1], vars);
    if (L !== 'en' && A.ai) {
      /* Regional languages: Gemini translation cached on this device; English until ready (shown, not silent) */
      const tr = A.ai.loadCached(L);
      if (tr && tr[key]) return A.util.fill(tr[key], vars);
    }
    return A.util.fill(row[0], vars);
  };
